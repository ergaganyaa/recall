"use client";

import { useState, useTransition } from "react";
import { recapStory } from "@/app/actions/assistant";
import type { ChatMessage } from "@/lib/types";
import { Sources } from "./assistant-chat";

/**
 * "Remind me what happened" on the book page. The server decides what the reader has read (from their own saved
 * position), writes the recap from only that text, and returns it with links to the chapters and paragraphs it
 * came from. Nothing about where the reader is comes from this component. It does not block the page: the button
 * just shows that it is working.
 */
export function RecapCard({ bookId, configured, started }: { bookId: string; configured: boolean; started: boolean }) {
  const [pending, startTransition] = useTransition();
  const [recap, setRecap] = useState<ChatMessage | null>(null);
  const [error, setError] = useState<string | null>(null);

  function run() {
    if (pending) return;
    setError(null);
    startTransition(async () => {
      try {
        const res = await recapStory(bookId);
        if (!res.ok) return setError(res.error);
        setRecap(res.data.find((m) => m.role === "assistant") ?? null);
      } catch {
        setError("Couldn't reach the server. Please try again.");
      }
    });
  }

  return (
    <div className="mt-3" data-testid="recap-card">
      <button
        type="button"
        onClick={run}
        disabled={pending || !configured || !started}
        aria-busy={pending}
        data-testid="recap-open"
        title={
          !configured
            ? "Add a Gemini API key to use the recap"
            : !started
              ? "Start reading first: a recap only covers what you have read"
              : "A short reminder of the story just before your place"
        }
        className="inline-flex items-center gap-1.5 rounded-full border border-border px-4 py-2 text-sm font-medium transition hover:border-accent hover:text-accent disabled:opacity-50 focus-visible:outline-2 focus-visible:outline-solid focus-visible:outline-accent"
      >
        <span aria-hidden>↺</span> {pending ? "Writing your recap…" : "Remind me what happened"}
      </button>
      {!configured && <p className="mt-1 text-xs text-muted">The recap needs a free Gemini API key (see the README).</p>}

      {error && (
        <p role="alert" className="mt-2 rounded-xl bg-danger/10 px-3 py-2 text-xs text-danger">
          {error}
        </p>
      )}

      {recap && (
        <div className="mt-3 rounded-xl bg-accent-soft px-4 py-3 text-sm" data-testid="recap-result">
          <p className="mb-1 text-xs font-medium uppercase tracking-wide text-muted">Story so far</p>
          <p className="whitespace-pre-wrap leading-relaxed">{recap.content}</p>
          {recap.sources && <Sources sources={recap.sources} />}
          <p className="mt-2 text-[0.7rem] text-muted">Based only on what you have read. Generated by AI; check the linked passages.</p>
        </div>
      )}
    </div>
  );
}
